// AIService abstracts the interaction with the LLM provider.
// GenerateSuggestion receives a Job (with log content) and returns a textual
// suggestion, a confidence score (0‑1), and an error if the LLM call fails.
type AIService interface {
	GenerateSuggestion(ctx context.Context, job models.Job) (suggestion string, confidence float64, err error)
}

