// AISuggester is a background worker that consumes job IDs from a RabbitMQ queue,
// fetches the corresponding job logs, invokes the AI engine to generate a suggestion,
// and persists the result.
//
// It is designed to be started once per process (e.g., from main.go) and runs until the
// supplied context is cancelled.
type AISuggester struct {
	logger      *zap.Logger
	jobRepo     repository.JobRepository
	aiRepo      repository.AIRepository
	aiService   AIService
	amqpConn    *amqp.Connection
	queueName   string
	prefetchCnt int
}

// NewAISuggester constructs a fully‑wired AISuggester.
//   - logger: structured logger (zap)
//   - jobRepo: repository for Job entities
//   - aiRepo: repository for AISuggestion entities
//   - aiService: service that talks to the LLM provider
//   - amqpConn: live RabbitMQ connection
//   - queueName: name of the queue that receives job IDs (e.g., "ai_suggestions")
//   - prefetchCnt: number of messages to pre‑fetch per consumer (controls concurrency)
func NewAISuggester(
	logger *zap.Logger,
	jobRepo repository.JobRepository,
	aiRepo repository.AIRepository,
	aiService AIService,
	amqpConn *amqp.Connection,
	queueName string,
	prefetchCnt int,
) *AISuggester {
	if prefetchCnt <= 0 {
		prefetchCnt = 1
	}
	return &AISuggester{
		logger:      logger,
		jobRepo:     jobRepo,
		aiRepo:      aiRepo,
		aiService:   aiService,
		amqpConn:    amqpConn,
		queueName:   queueName,
		prefetchCnt: prefetchCnt,
	}
}

// Start begins consuming messages from the configured RabbitMQ queue.
// It blocks until the context is cancelled or a fatal error occurs.
// Errors are logged and returned to the caller for visibility.
func (w *AISuggester) Start(ctx context.Context) error {
	ch, err := w.amqpConn.Channel()
	if err != nil {
		return fmt.Errorf("failed to open AMQP channel: %w", err)
	}
	// Ensure the channel is closed when the worker stops.
	go func() {
		<-ctx.Done()
		_ = ch.Close()
	}()

	// QoS: limit unacknowledged messages per consumer.
	if err := ch.Qos(w.prefetchCnt, 0, false); err != nil {
		return fmt.Errorf("failed to set QoS: %w", err)
	}

	// Declare the queue (idempotent). The queue is expected to be durable.
	_, err = ch.QueueDeclare(
		w.queueName,
		true,  // durable
		false, // auto‑delete
		false, // exclusive
		false, // no‑wait
		nil,   // arguments
	)
	if err != nil {
		return fmt.Errorf("failed to declare queue %s: %w", w.queueName, err)
	}

	msgs, err := ch.Consume(
		w.queueName,
		"",    // consumer tag (generated by server)
		false, // auto‑ack
		false, // exclusive
		false, // no‑local (not supported by RabbitMQ)
		false, // no‑wait
		nil,   // arguments
	)
	if err != nil {
		return fmt.Errorf("failed to start consuming from queue %s: %w", w.queueName, err)
	}

	w.logger.Info("AI suggester worker started", zap.String("queue", w.queueName), zap.Int("prefetch", w.prefetchCnt))

	// Process deliveries sequentially; concurrency is controlled via prefetch.
	for {
		select {
		case <-ctx.Done():
			w.logger.Info("AI suggester worker shutting down")
			return nil
		case d, ok := <-msgs:
			if !ok {
				// Channel closed – exit gracefully.
				w.logger.Info("AMQP delivery channel closed")
				return nil
			}
			if err := w.handleDelivery(d); err != nil {
				// Log the error; the message is NACKed inside handleDelivery.
				w.logger.Error("failed to handle delivery", zap.Error(err), zap.ByteString("body", d.Body))
			}
		}
	}
}

// handleDelivery processes a single AMQP delivery.
// It parses the payload, fetches the job, runs the AI suggestion pipeline,
// persists the suggestion, and acknowledges or NACKs the message accordingly.
func (w *AISuggester) handleDelivery(d amqp.Delivery) error {
	// Ensure we always ACK/NACK the message.
	defer func() {
		// If the message has already been ACKed/NACKed inside the processing flow,
		// this defer will be a no‑op because the channel will be closed.
		if d.Acknowledged || d.Rejected {
			return
		}
		// In case of unexpected panic, NACK and requeue.
		_ = d.Nack(false, true)
	}()

	// Parse payload – expected format: {"job_id":123}
	var payload struct {
		JobID int64 `json:"job_id"`
	}
	if err := json.Unmarshal(d.Body, &payload); err != nil {
		_ = d.Nack(false, false) // discard malformed messages
		return fmt.Errorf("invalid payload: %w", err)
	}
	if payload.JobID <= 0 {
		_ = d.Nack(false, false)
		return fmt.Errorf("invalid job_id %d", payload.JobID)
	}

	// Fetch the job from the DB.
	job, err := w.jobRepo.GetByID(context.Background(), payload.JobID)
	if err != nil {
		// Transient DB errors – requeue for later retry.
		_ = d.Nack(false, true)
		return fmt.Errorf("failed to fetch job %d: %w", payload.JobID, err)
	}
	if job == nil {
		// Job not found – discard the message.
		_ = d.Nack(false, false)
		return fmt.Errorf("job %d not found", payload.JobID)
	}

	// Skip if a suggestion already exists.
	if job.AISuggestionID != nil {
		_ = d.Ack(false)
		return nil
	}

	// Retrieve the raw log. If the log is stored in Redis, the repository abstracts that.
	logContent, err := w.jobRepo.GetLogContent(context.Background(), payload.JobID)
	if err != nil {
		_ = d.Nack(false, true)
		return fmt.Errorf("failed to retrieve logs for job %d: %w", payload.JobID, err)
	}
	if len(logContent) == 0 {
		// Empty logs – nothing to analyse. Ack to drop.
		_ = d.Ack(false)
		return fmt.Errorf("empty logs for job %d", payload.JobID)
	}

	// Call the AI service.
	suggestionText, confidence, err := w.aiService.GenerateSuggestion(context.Background(), models.Job{
		ID:        job.ID,
		Provider:  job.Provider,
		Repo:      job.Repo,
		Ref:       job.Ref,
		Status:    job.Status,
		Log:       logContent,
	})
	if err != nil {
		// AI failures are considered transient; requeue.
		_ = d.Nack(false, true)
		return fmt.Errorf("AI generation failed for job %d: %w", payload.JobID, err)
	}

	// Persist the suggestion.
	sugg := &models.AISuggestion{
		JobID:      job.ID,
		Text:       suggestionText,
		Confidence: confidence,
		CreatedAt:  time.Now().UTC(),
	}
	if err := w.aiRepo.Create(context.Background(), sugg); err != nil {
		_ = d.Nack(false, true)
		return fmt.Errorf("failed to store AI suggestion for job %d: %w", payload.JobID, err)
	}

	// Update the job to reference the new suggestion.
	if err := w.jobRepo.SetAISuggestionID(context.Background(), job.ID, sugg.ID); err != nil {
		_ = d.Nack(false, true)
		return fmt.Errorf("failed to link suggestion %d to job %d: %w", sugg.ID, job.ID, err)
	}

	// All good – ACK the message.
	if err := d.Ack(false); err != nil {
		return fmt.Errorf("failed to ACK delivery for job %d: %w", payload.JobID, err)
	}
	w.logger.Info("AI suggestion generated",
		zap.Int64("job_id", job.ID),
		zap.Int64("suggestion_id", sugg.ID),
		zap.Float64("confidence", confidence),
	)
	return nil
}

