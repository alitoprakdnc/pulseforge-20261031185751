// Severity represents the alert level.
type Severity string

const (
	SeverityInfo    Severity = "info"
	SeverityWarning Severity = "warning"
	SeverityCritical Severity = "critical"
)

// NotificationType defines the channel used for alert delivery.
type NotificationType string

const (
	NotificationEmail   NotificationType = "email"
	NotificationSlack   NotificationType = "slack"
	NotificationWebhook NotificationType = "webhook"
)

// NotificationRule describes how an alert should be delivered.
type NotificationRule struct {
	Type   NotificationType `json:"type"`   // email, slack, webhook
	Target string           `json:"target"` // email address, slack webhook URL, generic webhook URL
	Enabled bool            `json:"enabled"`
}

// Alert represents an incident generated by the platform.
type Alert struct {
	ID               uint               `json:"id" gorm:"primaryKey"`
	PipelineID       uint               `json:"pipeline_id" gorm:"index"`
	Title            string             `json:"title"`
	Message          string             `json:"message"`
	Severity         Severity           `json:"severity" gorm:"type:severity;index"`
	Rules            []NotificationRule `json:"rules" gorm:"-"`
	CreatedAt        time.Time          `json:"created_at"`
	UpdatedAt        time.Time          `json:"updated_at"`
}

// TableName overrides the default table name for GORM.
func (Alert) TableName() string {
	return "alerts"
}

// AlertRuleDB is the persistence model for NotificationRule.
type AlertRuleDB struct {
	ID        uint   `gorm:"primaryKey"`
	AlertID   uint   `gorm:"index;not null"`
	Type      string `gorm:"type:varchar(20);not null"`
	Target    string `gorm:"type:text;not null"`
	Enabled   bool   `gorm:"default:true"`
	CreatedAt time.Time
}

// Config holds configuration required by the AlertService.
type Config struct {
	SMTPHost     string
	SMTPPort     int
	SMTPUser     string
	SMTPPassword string

	// DefaultFrom is the email address used as the sender for all alerts.
	DefaultFrom string
}

// AlertService orchestrates alert persistence and notification delivery.
type AlertService struct {
	db         *gorm.DB
	redis      *redis.Client
	httpClient *http.Client
	logger     *zap.Logger
	cfg        Config
}

// NewAlertService creates a new instance of AlertService.
func NewAlertService(db *gorm.DB, redisClient *redis.Client, logger *zap.Logger, cfg Config) *AlertService {
	return &AlertService{
		db:         db,
		redis:      redisClient,
		httpClient: &http.Client{Timeout: 10 * time.Second},
		logger:     logger,
		cfg:        cfg,
	}
}

// CreateAlert persists the alert and its notification rules, then triggers delivery.
func (as *AlertService) CreateAlert(ctx context.Context, alert Alert) error {
	// Begin a transaction so alert and its rules are atomic.
	tx := as.db.WithContext(ctx).Begin()
	if tx.Error != nil {
		as.logger.Error("failed to begin transaction for alert creation", zap.Error(tx.Error))
		return tx.Error
	}

	if err := tx.Create(&alert).Error; err != nil {
		tx.Rollback()
		as.logger.Error("failed to insert alert", zap.Error(err))
		return err
	}

	// Persist notification rules.
	for _, rule := range alert.Rules {
		ruleDB := AlertRuleDB{
			AlertID: alert.ID,
			Type:    string(rule.Type),
			Target:  rule.Target,
			Enabled: rule.Enabled,
		}
		if err := tx.Create(&ruleDB).Error; err != nil {
			tx.Rollback()
			as.logger.Error("failed to insert alert rule", zap.Uint("alert_id", alert.ID), zap.Error(err))
			return err
		}
	}

	if err := tx.Commit().Error; err != nil {
		as.logger.Error("failed to commit alert transaction", zap.Error(err))
		return err
	}

	// Cache the alert ID in Redis for quick lookup (e.g., UI badge counters).
	if err := as.cacheAlertID(ctx, alert.ID); err != nil {
		// Non‑fatal – continue with notification.
		as.logger.Warn("failed to cache alert ID in Redis", zap.Uint("alert_id", alert.ID), zap.Error(err))
	}

	// Fire notifications asynchronously to avoid blocking the request path.
	go func(a Alert) {
		if err := as.sendNotifications(context.Background(), a); err != nil {
			as.logger.Error("failed to send alert notifications", zap.Uint("alert_id", a.ID), zap.Error(err))
		}
	}(alert)

	return nil
}

// cacheAlertID stores the alert ID in a Redis sorted set keyed by timestamp.
// This enables UI components to fetch recent alerts efficiently.
func (as *AlertService) cacheAlertID(ctx context.Context, alertID uint) error {
	key := "alerts:recent"
	score := float64(time.Now().Unix())
	member := fmt.Sprintf("%d", alertID)

	pipe := as.redis.TxPipeline()
	pipe.ZAdd(ctx, key, &redis.Z{Score: score, Member: member})
	pipe.ZRemRangeByScore(ctx, key, "0", fmt.Sprintf("%d", time.Now().Add(-24*time.Hour).Unix()))
	_, err := pipe.Exec(ctx)
	return err
}

// sendNotifications iterates over the alert's enabled rules and dispatches them.
func (as *AlertService) sendNotifications(ctx context.Context, alert Alert) error {
	// Load rules from DB to ensure we have the latest persisted state.
	var ruleDBs []AlertRuleDB
	if err := as.db.WithContext(ctx).Where("alert_id = ? AND enabled = true", alert.ID).Find(&ruleDBs).Error; err != nil {
		return fmt.Errorf("failed to fetch notification rules: %w", err)
	}

	var firstErr error
	for _, r := range ruleDBs {
		switch NotificationType(r.Type) {
		case NotificationEmail:
			if err := as.sendEmail(ctx, r.Target, alert); err != nil {
				as.logger.Error("email notification failed", zap.String("target", r.Target), zap.Error(err))
				if firstErr == nil {
					firstErr = err
				}
			}
		case NotificationSlack:
			if err := as.sendSlack(ctx, r.Target, alert); err != nil {
				as.logger.Error("slack notification failed", zap.String("target", r.Target), zap.Error(err))
				if firstErr == nil {
					firstErr = err
				}
			}
		case NotificationWebhook:
			if err := as.sendWebhook(ctx, r.Target, alert); err != nil {
				as.logger.Error("webhook notification failed", zap.String("target", r.Target), zap.Error(err))
				if firstErr == nil {
					firstErr = err
				}
			}
		default:
			as.logger.Warn("unknown notification type", zap.String("type", r.Type))
		}
	}
	return firstErr
}

// sendEmail delivers an alert via SMTP.
func (as *AlertService) sendEmail(ctx context.Context, to string, alert Alert) error {
	if as.cfg.SMTPHost == "" || as.cfg.SMTPPort == 0 {
		return fmt.Errorf("SMTP configuration missing")
	}

	subject := fmt.Sprintf("[PulseForge] %s – %s", alert.Severity, alert.Title)
	body := fmt.Sprintf("Alert ID: %d\nPipeline ID: %d\nSeverity: %s\n\n%s", alert.ID, alert.PipelineID, alert.Severity, alert.Message)

	// Build RFC 822 message.
	msg := bytes.NewBuffer(nil)
	fmt.Fprintf(msg, "From: %s\r\n", as.cfg.DefaultFrom)
	fmt.Fprintf(msg, "To: %s\r\n", to)
	fmt.Fprintf(msg, "Subject: %s\r\n", subject)
	fmt.Fprintf(msg, "MIME-Version: 1.0\r\n")
	fmt.Fprintf(msg, "Content-Type: text/plain; charset=\"utf-8\"\r\n")
	fmt.Fprintf(msg, "\r\n%s\r\n", body)

	addr := fmt.Sprintf("%s:%d", as.cfg.SMTPHost, as.cfg.SMTPPort)
	auth := smtp.PlainAuth("", as.cfg.SMTPUser, as.cfg.SMTPPassword, as.cfg.SMTPHost)

	// Use a cancellable context to respect request deadlines.
	done := make(chan error, 1)
	go func() {
		done <- smtp.SendMail(addr, auth, as.cfg.DefaultFrom, []string{to}, msg.Bytes())
	}()

	select {
	case <-ctx.Done():
		return ctx.Err()
	case err := <-done:
		return err
	}
}

// sendSlack posts a simple message to a Slack Incoming Webhook URL.
func (as *AlertService) sendSlack(ctx context.Context, webhookURL string, alert Alert) error {
	payload := map[string]string{
		"text": fmt.Sprintf("*[%s]* %s\nPipeline ID: %d\n%s", alert.Severity, alert.Title, alert.PipelineID, alert.Message),
	}
	data, err := json.Marshal(payload)
	if err != nil {
		return fmt.Errorf("failed to marshal slack payload: %w", err)
	}

	req, err := http.NewRequestWithContext(ctx, http.MethodPost, webhookURL, bytes.NewReader(data))
	if err != nil {
		return fmt.Errorf("failed to create slack request: %w", err)
	}
	req.Header.Set("Content-Type", "application/json")

	resp, err := as.httpClient.Do(req)
	if err != nil {
		return fmt.Errorf("slack request error: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		return fmt.Errorf("slack webhook returned status %d", resp.StatusCode)
	}
	return nil
}

// sendWebhook posts a JSON representation of the alert to an arbitrary endpoint.
func (as *AlertService) sendWebhook(ctx context.Context, endpoint string, alert Alert) error {
	payload := map[string]interface{}{
		"id":          alert.ID,
		"pipeline_id": alert.PipelineID,
		"title":       alert.Title,
		"message":     alert.Message,
		"severity":    alert.Severity,
		"timestamp":   alert.CreatedAt.UTC().Format(time.RFC3339),
	}
	data, err := json.Marshal(payload)
	if err != nil {
		return fmt.Errorf("failed to marshal webhook payload: %w", err)
	}

	req, err := http.NewRequestWithContext(ctx, http.MethodPost, endpoint, bytes.NewReader(data))
	if err != nil {
		return fmt.Errorf("failed to create webhook request: %w", err)
	}
	req.Header.Set("Content-Type", "application/json")
	req.Header.Set("User-Agent", "PulseForge-AlertService/1.0")

	resp, err := as.httpClient.Do(req)
	if err != nil {
		return fmt.Errorf("webhook request error: %w", err)
	}
	defer resp.Body.Close()

	if resp.StatusCode < 200 || resp.StatusCode >= 300 {
		return fmt.Errorf("webhook endpoint returned status %d", resp.StatusCode)
	}
	return nil
}

// ListRecentAlerts returns the most recent alerts limited by count.
// It reads from Redis first for speed; if the cache miss occurs it falls back to DB.
func (as *AlertService) ListRecentAlerts(ctx context.Context, limit int) ([]Alert, error) {
	if limit <= 0 {
		limit = 10
	}
	key := "alerts:recent"
	ids, err := as.redis.ZRevRange(ctx, key, 0, int64(limit-1)).Result()
	if err != nil && err != redis.Nil {
		as.logger.Warn("redis recent alerts lookup failed", zap.Error(err))
	}
	if len(ids) > 0 {
		var alerts []Alert
		if err := as.db.WithContext(ctx).Where("id IN ?", ids).Order("created_at DESC").Find(&alerts).Error; err == nil {
			return alerts, nil
		}
		// If DB fetch fails, fall back to full query below.
	}

	// Fallback: query DB directly.
	var alerts []Alert
	if err := as.db.WithContext(ctx).Order("created_at DESC").Limit(limit).Find(&alerts).Error; err != nil {
		return nil, fmt.Errorf("failed to fetch recent alerts: %w", err)
	}
	return alerts, nil
}

// ResolveAlert marks an alert as resolved and optionally notifies stakeholders.
// For simplicity we only update the DB; notification logic can be extended later.
func (as *AlertService) ResolveAlert(ctx context.Context, alertID uint) error {
	result := as.db.WithContext(ctx).Model(&Alert{}).Where("id = ?", alertID).Update("severity", SeverityInfo)
	if result.Error != nil {
		return fmt.Errorf("failed to resolve alert %d: %w", alertID, result.Error)
	}
	if result.RowsAffected == 0 {
		return fmt.Errorf("no alert found with id %d", alertID)
	}
	// Optionally, we could emit a "resolved" webhook.
	return nil
}

// Helper to translate PostgreSQL constraint errors into user‑friendly messages.
func pgErrorMessage(err error) string {
	var pgErr *pgconn.PgError
	if ok := errorAs(err, &pgErr); ok {
		switch pgErr.Code {
		case "23505":
			return "duplicate entry"
		case "23503":
			return "referential integrity violation"
		}
	}
	return err.Error()
}

// errorAs is a thin wrapper around errors.As to keep imports tidy.
func errorAs(err error, target interface{}) bool {
	return errors.As(err, target)
}