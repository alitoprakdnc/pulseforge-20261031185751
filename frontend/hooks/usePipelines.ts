import useSWR, { SWRResponse } from 'swr';
import api from '../utils/api';

/**
 * Pipeline entity shape as returned by the backend.
 * Adjust fields to match the actual API contract if needed.
 */
export interface Pipeline {
  /** UUID of the pipeline */
  id: string;
  /** Human‑readable name (e.g. repository name) */
  name: string;
  /** CI provider: "github", "gitlab", "circleci" */
  provider: 'github' | 'gitlab' | 'circleci';
  /** Repository identifier (owner/repo) */
  repository: string;
  /** URL to the provider’s pipeline page */
  url: string;
  /** Timestamp of creation (ISO‑8601) */
  created_at: string;
  /** Timestamp of last update (ISO‑8601) */
  updated_at: string;
  /** Optional health‑check endpoint generated by PulseForge */
  health_endpoint?: string;
}

/**
 * Parameters accepted by the hook – currently pagination only.
 */
export interface UsePipelinesParams {
  /** Page number (1‑based). If omitted the backend default is used. */
  page?: number;
  /** Number of items per page. */
  limit?: number;
}

/**
 * Return type of the hook.
 */
export interface UsePipelinesResult {
  /** Array of pipelines – undefined while loading. */
  pipelines?: Pipeline[];
  /** True while the request is in flight. */
  isLoading: boolean;
  /** True if the request failed. */
  isError: boolean;
  /** SWR mutate function – callers can trigger a re‑fetch. */
  mutate: () => Promise<Pipeline[] | undefined>;
  /** Indicates if SWR is currently revalidating (background refresh). */
  isValidating: boolean;
}

/**
 * SWR fetcher that uses the pre‑configured Axios instance.
 */
const fetcher = async (url: string): Promise<Pipeline[]> => {
  const response = await api.get<Pipeline[]>(url);
  return response.data;
};

/**
 * Custom hook that fetches the list of pipelines with SWR.
 *
 * It provides sensible defaults for caching, error retries and
 * disables automatic revalidation on window focus to avoid
 * unnecessary load on the API.
 *
 * @param params Optional pagination parameters.
 * @returns Hook result containing data, loading/error flags and a mutate function.
 */
export const usePipelines = (
  params?: UsePipelinesParams,
): UsePipelinesResult => {
  // Build query string only when needed – keeps the URL clean.
  const query = new URLSearchParams();
  if (params?.page) query.append('page', String(params.page));
  if (params?.limit) query.append('limit', String(params.limit));

  const endpoint = `/pipelines${query.toString() ? `?${query}` : ''}`;

  const {
    data,
    error,
    mutate,
    isValidating,
  }: SWRResponse<Pipeline[], any> = useSWR<Pipeline[]>(endpoint, fetcher, {
    // Do not revalidate on focus to keep traffic predictable.
    revalidateOnFocus: false,
    // Keep data for 1 minute to serve stale‑while‑revalidate scenarios.
    dedupingInterval: 60_000,
    // Retry a few times before surfacing the error.
    errorRetryCount: 3,
    // Back‑off strategy (default exponential) is fine.
  });

  return {
    pipelines: data,
    isLoading: !error && !data,
    isError: !!error,
    mutate: async () => {
      // mutate returns the fresh data (or undefined on error)
      const fresh = await mutate();
      return fresh;
    },
    isValidating,
  };
};